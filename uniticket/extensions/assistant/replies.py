from typing import Literal, TypedDict

"""
Think of TextReply as a quick reply generated by an LLM and presented to the user as a selectable option.

For example, the LLM might ask, "Are you enrolled in a Master's degree program?" and generate two quick replies: "Yes" and "No".

This is a nice-to-have feature and should be treated as an initial proof of concept rather than a strict implementation requirement.

You're encouraged to explore alternatives and decide how to design and implement this feature effectively, keeping future extensibility in mind.
"""
class TextReply(TypedDict):
    type: Literal["reply_text"]
    label: str
    message: str

"""
Must have
"""
class TicketReply(TypedDict):
    type: Literal["ticket"]
    label: str
    title: str
    ticket_id: int  # ID della TicketCategory di cui aprire il modulo.


Reply = TextReply | TicketReply
